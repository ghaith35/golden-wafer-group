// Prepares the Next.js standalone output for Electron packaging.
//
// `next build` with output:"standalone" emits a self-contained server but does
// NOT copy static assets — they must be placed next to server.js. This also
// confirms the offline-DB resources (generated SQLite client + DDL + seed DB)
// were traced in via next.config's outputFileTracingIncludes.
import { cpSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { createPublicKey } from "node:crypto";
import { resolve } from "node:path";

const ROOT = process.cwd();
const STANDALONE = resolve(ROOT, ".next/standalone");

if (!existsSync(resolve(STANDALONE, "server.js"))) {
  console.error("Missing .next/standalone/server.js — run `next build` first.");
  process.exit(1);
}

// Static assets (CSS/JS chunks) and public/ files.
cpSync(resolve(ROOT, ".next/static"), resolve(STANDALONE, ".next/static"), {
  recursive: true,
});
if (existsSync(resolve(ROOT, "public"))) {
  cpSync(resolve(ROOT, "public"), resolve(STANDALONE, "public"), { recursive: true });
}
// The desktop pipeline builds the seed after Next has already traced files.
const seed = resolve(ROOT, "prisma/sqlite-seed.db");
if (existsSync(seed)) {
  cpSync(seed, resolve(STANDALONE, "prisma/sqlite-seed.db"));
}

// Sanity-check the offline-DB resources that Electron's first run depends on.
const required = [
  ".next/standalone/prisma/sqlite-init.sql",
  ".next/standalone/src/generated/prisma-sqlite/index.js",
  ".next/standalone/prisma/sqlite-seed.db",
  // Runtime DB drivers (loaded via eval-require — Turbopack can't trace them,
  // so next.config forces them in; a partial copy boots but 500s every query).
  ".next/standalone/node_modules/@prisma/adapter-libsql/dist/index-node.js",
  ".next/standalone/node_modules/@prisma/client-runtime-utils/dist/index.js",
  ".next/standalone/node_modules/libsql/index.js",
  ".next/standalone/node_modules/@libsql/client/lib-cjs/node.js",
];
const missing = required.filter((p) => !existsSync(resolve(ROOT, p)));
if (missing.length) {
  console.error(
    "Standalone is missing offline-DB resources (check next.config tracing):\n  " +
      missing.join("\n  "),
  );
  process.exit(1);
}

console.log("✓ standalone prepared for Electron (static, public, offline-db resources).");

// ── Target validation ─────────────────────────────────────────────────────
// Usage: node scripts/electron-prepare.mjs [--target=win|mac]
// A Windows installer built on macOS ships darwin-arm64 .node files unless
// scripts/fix-standalone-win.mjs ran first → the server child crashes and
// the app is "not reachable". Refuse to package that mistake silently.
const PREPARE_TARGET = (process.argv.find((a) => a.startsWith("--target=")) || "").split("=")[1] || "";
if (PREPARE_TARGET === "win") {
  const winBinding = resolve(STANDALONE, "node_modules/@libsql/win32-x64-msvc");
  const darwinOnly =
    existsSync(resolve(STANDALONE, "node_modules/@libsql/darwin-arm64")) && !existsSync(winBinding);
  if (darwinOnly) {
    console.error(
      "!! win target but standalone carries ONLY darwin-arm64 native bindings.\n" +
        "!! Run: node scripts/fix-standalone-win.mjs --target=win  (or build on Windows / CI).",
    );
    process.exit(1);
  }
  console.log("✓ win target: native bindings check passed.");
}

// Per-client stage: build-client.json is baked into the installer so each
// client's EXE/DMG knows its own subdomain (+tunnel token). Generated by
// scripts/set-client.mjs (gitignored, may carry a secret); default to an
// empty identity so generic builds keep working without it.
import { mkdirSync } from "node:fs";
const STAGE = resolve(ROOT, "build/stage");
mkdirSync(STAGE, { recursive: true });
const stagedId = resolve(STAGE, "build-client.json");
if (!existsSync(stagedId)) {
  const rootId = resolve(ROOT, "build-client.json");
  if (existsSync(rootId)) {
    cpSync(rootId, stagedId);
    console.log("✓ staged per-client identity from build-client.json");
  } else {
    writeFileSync(stagedId, JSON.stringify({ client: null, domain: null, tunnelToken: null }, null, 2) + "\n");
    console.log("✓ no build-client.json — staged empty client identity (generic build)");
  }
}
// Connector binary is staged by scripts/dist-client.mjs; warn (don't fail)
// so generic local builds still package without internet-serving capability.
if (!existsSync(resolve(STAGE, "bin/cloudflared")) && !existsSync(resolve(STAGE, "bin/cloudflared.exe"))) {
  console.error("!! no connector staged in build/stage/bin — this installer will be LAN-only (no internet phones).");
}

// License key check (runtime, not string search): electron/dist/license.js is
// already OBFUSCATED at this point (stringArray/base64 + split strings), so a
// REPLACE_AT_DEPLOY grep can never match. The real bake happens pre-obfuscation
// in scripts/obfuscate-electron.mjs. Here we just verify the outcome by loading
// the module: fail-closed unless ALLOW_UNLICENSED_BUILD=1.
const licenseJs = resolve(ROOT, "electron/dist/license.js");
if (existsSync(licenseJs)) {
  try {
    const { createRequire } = await import("node:module");
    const lic = createRequire(import.meta.url)(licenseJs);
    const dev = typeof lic.isDevBuild === "function" ? lic.isDevBuild() : true;
    if (dev) {
      if (process.env.ALLOW_UNLICENSED_BUILD === "1") {
        console.error("!! ALLOW_UNLICENSED_BUILD=1 — packaged EXE will be LICENSE-INERT (dev bypass).");
      } else {
        console.error(
          "!! electron/dist/license.js has NO baked license key (dev bypass) — refusing to package.",
        );
        process.exit(1);
      }
    } else {
      console.log("✓ license key verified baked (runtime check)");
    }
  } catch (e) {
    console.error(`!! license runtime check failed (${String(e)}) — refusing to package blind.`);
    if (process.env.ALLOW_UNLICENSED_BUILD !== "1") process.exit(1);
  }
}
