# Golden Wafer Group: Android splash screens + Electron tray/loading icon from the badge.
# Regenerate: python3 scripts/make-splash-and-tray.py
import os, base64, io
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android/app/src/main/res")
badge = Image.open(os.path.join(ROOT, "public/icons/logo-source.png")).convert("RGB")
BG = badge.getpixel((4, 4))
TARGETS = [("drawable-port-mdpi",320,480),("drawable-port-hdpi",480,800),("drawable-port-xhdpi",720,1280),
 ("drawable-port-xxhdpi",960,1600),("drawable-port-xxxhdpi",1280,1920),("drawable-land-mdpi",480,320),
 ("drawable-land-hdpi",800,480),("drawable-land-xhdpi",1280,720),("drawable-land-xxhdpi",1600,960),
 ("drawable-land-xxxhdpi",1920,1280),("drawable",1080,1920)]
for d, w, h in TARGETS:
    side = int(min(w, h) * 0.78)
    im = Image.new("RGB", (w, h), BG)
    im.paste(badge.resize((side, side), Image.LANCZOS), ((w - side)//2, (h - side)//2))
    im.save(os.path.join(RES, d, "splash.png"), optimize=True)
buf = io.BytesIO(); badge.resize((96, 96), Image.LANCZOS).save(buf, "PNG", optimize=True)
b64 = base64.b64encode(buf.getvalue()).decode()
chunks = [b64[i:i+120] for i in range(0, len(b64), 120)]
with open(os.path.join(ROOT, "electron/tray-icon.ts"), "w") as f:
    f.write("// Generated by scripts/make-splash-and-tray.py (Golden Wafer Group badge)\nexport const TRAY_ICON_B64 =\n  " +
            " +\n  ".join('"%s"' % c for c in chunks) + ";\n")
