// Distribuili desktop licensing (verify-only, Jafraa pattern).
// The Electron main process verifies server-signed activation/trial tokens
// BEFORE starting the local database or app. The private key lives ONLY on
// the license server; the app holds the public key (baked at deploy time).
//
// Dev bypass: while DISTRIBUILI_LICENSE_PUBLIC_KEY_DER_B64 is the placeholder,
// every machine reports entitled (never ship a placeholder build to customers).

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

// Ed25519 PUBLIC key (SPKI, base64 DER). Pair of the server's LICENSE_PRIVATE_KEY.
// Generated by: node scripts/gen-license-keys.mjs — injected at package time
// by scripts/electron-prepare.mjs (never commit a real key here).
const DISTRIBUILI_LICENSE_PUBLIC_KEY_DER_B64 = "REPLACE_AT_DEPLOY";

/// Exposed so main.ts can hand the SAME key to the bundled Next server
/// (DISTRIBUILI_LICENSE_PUBLIC_KEY env → server-side gate).
export function publicKeyB64(): string {
  return DISTRIBUILI_LICENSE_PUBLIC_KEY_DER_B64;
}

/// True when the public key was never baked (an explicit ALLOW_UNLICENSED_BUILD
/// dev build). Production builds with a real key are never dev builds.
export function isDevBuild(): boolean {
  return isPlaceholder();
}

export interface LicensePayload { machineId: string; label: string; key?: string; issuedAt: string; v: 1 }
export interface TrialPayload { kind: "trial"; machineId: string; trialStart: string; trialEnd: string; v: 1 }
export interface DeviceSpecs { [k: string]: string | number | undefined }

function isPlaceholder(): boolean {
  return !DISTRIBUILI_LICENSE_PUBLIC_KEY_DER_B64 || DISTRIBUILI_LICENSE_PUBLIC_KEY_DER_B64 === "REPLACE_AT_DEPLOY";
}

function getPublicKey(): crypto.KeyObject {
  return crypto.createPublicKey({
    key: Buffer.from(DISTRIBUILI_LICENSE_PUBLIC_KEY_DER_B64, "base64"),
    format: "der",
    type: "spki",
  });
}

function fromB64url(s: string): Buffer {
  return Buffer.from(s.replace(/-/g, "+").replace(/_/g, "/"), "base64");
}

function verifySig(token: string): unknown | null {
  try {
    const [p, s] = token.trim().split(".");
    if (!p || !s) return null;
    if (!crypto.verify(null, Buffer.from(p, "utf8"), getPublicKey(), fromB64url(s))) return null;
    return JSON.parse(fromB64url(p).toString("utf8"));
  } catch {
    return null;
  }
}

export function verifyActivationToken(token: string, machineId: string): LicensePayload | null {
  if (isPlaceholder()) return null;
  const payload = verifySig(token) as LicensePayload | null;
  if (!payload) return null;
  if ((payload as unknown as TrialPayload).kind === "trial") return null;
  if (payload.v !== 1 || payload.machineId !== machineId) return null;
  return payload;
}

export function verifyTrialToken(token: string, machineId: string): TrialPayload | null {
  if (isPlaceholder()) return null;
  const payload = verifySig(token) as TrialPayload | null;
  if (!payload) return null;
  if (payload.kind !== "trial" || payload.v !== 1 || payload.machineId !== machineId) return null;
  if (!payload.trialStart || !payload.trialEnd) return null;
  return payload;
}

// ── Token files ─────────────────────────────────────────────────────────────
const activationFile = (d: string) => path.join(d, "activation.lic");
const trialFile = (d: string) => path.join(d, "trial.lic");
const clockHwFile = (d: string) => path.join(d, "clock.hw");

function readFileTrim(p: string): string | null {
  try { return fs.existsSync(p) ? (fs.readFileSync(p, "utf8").trim() || null) : null; } catch { return null; }
}

export function writeActivation(dataDir: string, token: string): void {
  fs.writeFileSync(activationFile(dataDir), token.trim(), "utf8");
}
export function writeTrial(dataDir: string, token: string): void {
  fs.writeFileSync(trialFile(dataDir), token.trim(), "utf8");
}
export function clearActivation(dataDir: string): void {
  try { fs.rmSync(activationFile(dataDir), { force: true }); } catch { /* best-effort */ }
}
export function clearTrial(dataDir: string): void {
  try { fs.rmSync(trialFile(dataDir), { force: true }); } catch { /* best-effort */ }
}

/// Nuclear option for remote lock: delete every token + the clock, so a
/// replanted old .lic can never resurrect the install. The sticky flag in
/// main.ts (safeStorage-encrypted) is what actually keeps it dead.
export function wipeAllTokens(dataDir: string): void {
  clearActivation(dataDir);
  clearTrial(dataDir);
  try { fs.rmSync(clockHwFile(dataDir), { force: true }); } catch { /* best-effort */ }
}

// Monotonic clock highwater — blocks extending a trial by rolling the clock back.
function effectiveNow(dataDir: string): number {
  const systemNow = Date.now();
  let hw = 0;
  const raw = readFileTrim(clockHwFile(dataDir));
  if (raw) hw = Number(raw) || 0;
  const now = Math.max(systemNow, hw);
  if (now > hw) { try { fs.writeFileSync(clockHwFile(dataDir), String(now), "utf8"); } catch { /* best-effort */ } }
  return now;
}

export interface Entitlement {
  activated: boolean;
  inTrial: boolean;
  expired: boolean;
  daysLeft: number;
  trialEnd: string | null;
  activationKey: string | null;
  machineId: string;
  devBypass: boolean;
}

export function getEntitlement(dataDir: string, machineId: string): Entitlement {
  if (isPlaceholder()) {
    return { activated: true, inTrial: false, expired: false, daysLeft: -1, trialEnd: null, activationKey: null, machineId, devBypass: true };
  }
  const act = readFileTrim(activationFile(dataDir));
  if (act && verifyActivationToken(act, machineId)) {
    const payload = verifySig(act) as LicensePayload;
    return { activated: true, inTrial: false, expired: false, daysLeft: -1, trialEnd: null, activationKey: payload.key ?? null, machineId, devBypass: false };
  }
  const trial = readFileTrim(trialFile(dataDir));
  if (trial) {
    const payload = verifyTrialToken(trial, machineId);
    if (payload) {
      const now = effectiveNow(dataDir);
      const end = new Date(payload.trialEnd).getTime();
      if (now <= end) {
        const daysLeft = Math.max(0, Math.ceil((end - now) / 86400000));
        return { activated: false, inTrial: true, expired: false, daysLeft, trialEnd: payload.trialEnd, activationKey: null, machineId, devBypass: false };
      }
      return { activated: false, inTrial: false, expired: true, daysLeft: 0, trialEnd: payload.trialEnd, activationKey: null, machineId, devBypass: false };
    }
  }
  return { activated: false, inTrial: false, expired: false, daysLeft: 0, trialEnd: null, activationKey: null, machineId, devBypass: false };
}

// ── License server HTTP helpers ─────────────────────────────────────────────
// Small JSON client (register / trial / activation / redeem). Fail-soft: the
// app stays fully usable offline; these run only on explicit user actions.
type Json = Record<string, unknown>;

function postJson(url: string, body: Json, timeoutMs = 20000): Promise<{ status: number; body: Json }> {
  return new Promise((resolve, reject) => {
    const lib = url.startsWith("https") ? require("node:https") : require("node:http");
    const data = JSON.stringify(body);
    const req = lib.request(url, { method: "POST", headers: { "Content-Type": "application/json", "Content-Length": Buffer.byteLength(data) }, timeout: timeoutMs }, (res: import("node:http").IncomingMessage) => {
      let raw = "";
      res.on("data", (c: Buffer) => { raw += c; });
      res.on("end", () => {
        try { resolve({ status: res.statusCode ?? 0, body: JSON.parse(raw || "{}") as Json }); }
        catch { resolve({ status: res.statusCode ?? 0, body: {} }); }
      });
    });
    req.on("error", reject);
    req.on("timeout", () => { req.destroy(); reject(new Error("timeout")); });
    req.write(data);
    req.end();
  });
}

function getJson(url: string, timeoutMs = 20000): Promise<{ status: number; body: Json }> {
  return new Promise((resolve, reject) => {
    const lib = url.startsWith("https") ? require("node:https") : require("node:http");
    const req = lib.get(url, { timeout: timeoutMs }, (res: import("node:http").IncomingMessage) => {
      let raw = "";
      res.on("data", (c: Buffer) => { raw += c; });
      res.on("end", () => {
        try { resolve({ status: res.statusCode ?? 0, body: JSON.parse(raw || "{}") as Json }); }
        catch { resolve({ status: res.statusCode ?? 0, body: {} }); }
      });
    });
    req.on("error", reject);
    req.on("timeout", () => { req.destroy(); reject(new Error("timeout")); });
  });
}

export interface TrialInfo { label?: string; phone?: string; specs?: DeviceSpecs }

export interface MachineInfo {
  phone?: string;
  workshop?: string;
  name?: string;
  contactName?: string;
  city?: string;
  email?: string;
}

export async function registerMachine(serverUrl: string, machineId: string, label: string, phone?: string, specs?: DeviceSpecs, info?: MachineInfo): Promise<void> {
  try {
    await postJson(`${serverUrl}/api/license/register`, { machineId, label, phone, specs, ...info });
  } catch { /* fail-soft: registration is informational */ }
}

export async function requestTrial(serverUrl: string, machineId: string, info: TrialInfo): Promise<{ token?: string; activated?: boolean; error?: string; revoked?: boolean }> {
  try {
    const { body } = await postJson(`${serverUrl}/api/license/trial`, { machineId, ...info });
    return body as { token?: string; activated?: boolean; error?: string; revoked?: boolean };
  } catch {
    return { error: "network" };
  }
}

export async function issueActivation(serverUrl: string, machineId: string): Promise<string | null> {
  try {
    const { body } = await postJson(`${serverUrl}/api/license/activate`, { machineId });
    const token = body.token;
    return typeof token === "string" && verifyActivationToken(token, machineId) ? token : null;
  } catch {
    return null;
  }
}

export async function redeemActivationKey(serverUrl: string, machineId: string, key: string, label: string, specs?: DeviceSpecs, info?: MachineInfo): Promise<{ token?: string; error?: string }> {
  try {
    const { body } = await postJson(`${serverUrl}/api/license/redeem`, { machineId, key, label, specs, ...info });
    const token = body.token;
    if (typeof token === "string" && verifyActivationToken(token, machineId)) return { token };
    return { error: typeof body.error === "string" ? body.error : "invalid" };
  } catch {
    return { error: "network" };
  }
}

export async function pullActivation(serverUrl: string, machineId: string): Promise<{ token?: string; revoked?: boolean; trialEnded?: boolean }> {
  try {
    const { body } = await getJson(`${serverUrl}/api/license/status?machineId=${encodeURIComponent(machineId)}`);
    const out: { token?: string; revoked?: boolean; trialEnded?: boolean } = {};
    if (body.revoked === true) out.revoked = true;
    if (body.trialEnded === true) out.trialEnded = true;
    if (typeof body.token === "string" && verifyActivationToken(body.token, machineId)) out.token = body.token;
    return out;
  } catch {
    return {};
  }
}
